from direct.directnotify import DirectNotifyGlobal
from direct.distributed.DistributedObjectAI import DistributedObjectAI
from otp.otpbase import OTPGlobals

# what the inviter's window is told when the invitation is first looked at (FriendInviter.__friendConsidering)
CONSIDERING_OK = 1
CONSIDERING_NOT_AVAILABLE = 0
CONSIDERING_ALREADY_FRIENDS = 2
CONSIDERING_SELF = 3
# what the invitee answers (FriendInvitee) and what the inviter is told in the end (FriendInviter.__friendResponse)
RESPONSE_NO = 0
RESPONSE_YES = 1
RESPONSE_RETRACTED = 2          # the invitee closed the window without answering
RESPONSE_TOO_MANY = 3           # the invitee's friends list is full


class FriendManagerAI(DistributedObjectAI):
    """Toon-to-toon friend invitations inside one district. One of these is generated by every district's AI; a client
    finds the one of its own district and talks to it (a toon can only invite someone it is standing next to)."""
    notify = DirectNotifyGlobal.directNotify.newCategory('FriendManagerAI')

    def __init__(self, air):
        DistributedObjectAI.__init__(self, air)
        self.nextContext = 1
        self.invites = {}               # context -> {'inviter': avId, 'invitee': avId, 'asked': 0 or 1}

    def delete(self):
        self.invites = {}
        DistributedObjectAI.delete(self)

    # ---- helpers
    def __toon(self, avId):
        return self.air.doId2do.get(avId)

    def __isFriend(self, toon, otherId):
        for pair in toon.getFriendsList():
            if pair[0] == otherId:
                return True
        return False

    def __invitationFor(self, inviteeId):
        for context, invite in self.invites.items():
            if invite['invitee'] == inviteeId:
                return context
        return None

    def __forget(self, context):
        self.invites.pop(context, None)

    def __prune(self):
        # drop invitations whose toons have left the district
        for context, invite in list(self.invites.items()):
            if invite['inviter'] not in self.air.doId2do or invite['invitee'] not in self.air.doId2do:
                del self.invites[context]

    def __makeFriends(self, a, b):
        for toon, other in ((a, b), (b, a)):
            toon.extendFriendsList(other.getDoId(), 0)
            toon.d_setFriendsList(toon.getFriendsList())
            if hasattr(toon, 'sendFriendDetails'):
                toon.sendFriendDetails()
        try:
            self.air.toonPresence.sendUpdate('friendshipMade', [a.getDoId(), b.getDoId()])
        except Exception:
            self.notify.warning('could not tell the presence service about the new friends')
        questManager = getattr(self.air, 'questManager', None)
        if questManager:
            for toon, other in ((a, b), (b, a)):
                try:
                    questManager.toonMadeFriend(toon, other)
                except Exception:
                    self.notify.warning('toonMadeFriend failed for %s' % toon.getDoId())

    # ---- from the inviter
    def friendQuery(self, inviteeId):
        self.__prune()
        inviterId = self.air.getAvatarIdFromSender()
        inviter = self.__toon(inviterId)
        if inviter is None:
            return
        invitee = self.__toon(inviteeId)
        if inviterId == inviteeId:
            self.sendUpdateToAvatarId(inviterId, 'friendConsidering', [CONSIDERING_SELF, 0])
        elif invitee is None or not hasattr(invitee, 'getFriendsList'):
            self.sendUpdateToAvatarId(inviterId, 'friendConsidering', [CONSIDERING_NOT_AVAILABLE, 0])
        elif self.__isFriend(inviter, inviteeId):
            self.sendUpdateToAvatarId(inviterId, 'friendConsidering', [CONSIDERING_ALREADY_FRIENDS, 0])
        elif self.__invitationFor(inviteeId) is not None:
            # someone else is already asking this toon
            self.sendUpdateToAvatarId(inviterId, 'friendConsidering', [CONSIDERING_NOT_AVAILABLE, 0])
        else:
            context = self.nextContext
            self.nextContext += 1
            self.invites[context] = {'inviter': inviterId, 'invitee': inviteeId, 'asked': 0}
            self.sendUpdateToAvatarId(inviteeId, 'inviteeFriendQuery',
                                      [inviterId, inviter.getName(), inviter.dna.makeNetString(), context])
            self.notify.debug('friendQuery: %s asks %s (context %s)' % (inviterId, inviteeId, context))

    def cancelFriendQuery(self, context):
        sender = self.air.getAvatarIdFromSender()
        invite = self.invites.get(context)
        if invite is None or invite['inviter'] != sender:
            return
        # the invitee's window is closed; it answers with inviteeAcknowledgeCancel, which clears the invitation
        self.sendUpdateToAvatarId(invite['invitee'], 'inviteeCancelFriendQuery', [context])

    # ---- from the invitee
    def inviteeFriendConsidering(self, yesNo, context):
        sender = self.air.getAvatarIdFromSender()
        invite = self.invites.get(context)
        if invite is None or invite['invitee'] != sender:
            return
        invite['asked'] = 1
        self.sendUpdateToAvatarId(invite['inviter'], 'friendConsidering', [yesNo, context])
        if yesNo != CONSIDERING_OK:
            self.__forget(context)

    def inviteeFriendResponse(self, yesNoMaybe, context):
        sender = self.air.getAvatarIdFromSender()
        invite = self.invites.get(context)
        if invite is None or invite['invitee'] != sender:
            return
        self.__forget(context)
        inviter = self.__toon(invite['inviter'])
        invitee = self.__toon(sender)
        if yesNoMaybe == RESPONSE_YES and inviter is not None and invitee is not None:
            if len(invitee.getFriendsList()) >= OTPGlobals.MaxFriends:
                answer = RESPONSE_TOO_MANY
            elif len(inviter.getFriendsList()) >= OTPGlobals.MaxFriends:
                answer = RESPONSE_NO
            else:
                self.__makeFriends(inviter, invitee)
                answer = RESPONSE_YES
        elif yesNoMaybe == RESPONSE_TOO_MANY:
            answer = RESPONSE_TOO_MANY
        else:
            answer = RESPONSE_NO
        if inviter is not None:
            self.sendUpdateToAvatarId(invite['inviter'], 'friendResponse', [answer, context])

    def inviteeAcknowledgeCancel(self, context):
        sender = self.air.getAvatarIdFromSender()
        invite = self.invites.get(context)
        if invite is not None and invite['invitee'] == sender:
            self.__forget(context)

    # ---- secret friends are not offered
    def requestSecret(self):
        self.sendUpdateToAvatarId(self.air.getAvatarIdFromSender(), 'requestSecretResponse', [0, ''])

    def submitSecret(self, secret):
        self.sendUpdateToAvatarId(self.air.getAvatarIdFromSender(), 'submitSecretResponse', [0, 0])
